"""MetaTrader 5 constants.

These mirror the values exported by the ``MetaTrader5`` package so the copier
logic (and its tests) can run without that Windows-only package installed.
"""

# Order / position types
ORDER_TYPE_BUY = 0
ORDER_TYPE_SELL = 1
