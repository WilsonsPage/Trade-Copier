# Mirror image of each order type, used by the "reverse" option.
# A buy limit (buy below market) mirrors to a sell stop (sell below market), etc.
REVERSE_TYPE = {
    ORDER_TYPE_BUY: ORDER_TYPE_SELL,
    ORDER_TYPE_SELL: ORDER_TYPE_BUY,
    ORDER_TYPE_BUY_LIMIT: ORDER_TYPE_SELL_STOP,
    ORDER_TYPE_SELL_STOP: ORDER_TYPE_BUY_LIMIT,
    ORDER_TYPE_SELL_LIMIT: ORDER_TYPE_BUY_STOP,
    ORDER_TYPE_BUY_STOP: ORDER_TYPE_SELL_LIMIT,
}

